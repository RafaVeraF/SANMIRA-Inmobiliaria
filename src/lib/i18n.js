export const LANGS = ['es', 'en', 'de'];

function detect() {
  const saved = localStorage.getItem('sanmira.lang');
  if (LANGS.includes(saved)) return saved;
  const nav = (navigator.language || 'es').slice(0, 2);
  return LANGS.includes(nav) ? nav : 'en';
}

let current = detect();

export const getLang = () => current;

export function t(key) {
  return dict[current]?.[key] ?? dict.es[key] ?? key;
}

/** Campo traducido de un registro: field_es / field_en / field_de con respaldo en español. */
export function tf(row, field) {
  return row?.[`${field}_${current}`] || row?.[`${field}_es`] || '';
}

export function applyI18n(root = document) {
  document.documentElement.lang = current;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-lang]').forEach((el) => {
    el.classList.toggle('underline', el.dataset.lang === current);
    el.setAttribute('aria-pressed', String(el.dataset.lang === current));
  });
}

const listeners = new Set();
export const onLangChange = (fn) => listeners.add(fn);

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  current = lang;
  localStorage.setItem('sanmira.lang', lang);
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}

/** Conecta los botones [data-lang] de la página. */
export function bindLangSwitch(root = document) {
  root.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
}
